def ev(table, name, f, lag=0.0, first=1, last=None):
    keys = table.get(name)
    if not keys:
        return BASE[name]
    if last is not None and lag:
        # overlap fades out over the last frames so the clip lands on its final pose
        lag *= max(0.0, min(1.0, (last - f) / 6.0))
    t = f - lag
    if name.startswith('toe_'):
        # stepped: a toe is either flat on the floor (NONE) or bent by a value
        v = keys[0][1]
        for k in keys:
            if k[0] <= t + 1e-6:
                v = k[1]
        return v
    if t < first:
        t = first
    if last is not None and t > last:
        t = last
    v0 = keys[0][1]
    if isinstance(v0, tuple):
        return tuple(curve(t, [(k[0], k[1][i], k[2] if len(k) > 2 else 'a') for k in keys]) for i in range(len(v0)))
    return curve(t, keys)


def params(table, f, polish=True, length=None):
    P = {}
    for name in BASE:
        P[name] = ev(table, name, f, LAG.get(name, 0.0) if polish else 0.0, 1, length)
    return P


def apply(rig, P, sig=None, f=0):
    body = Body(rig)
    body.pelvis(P['pel'], *P['pelr'])
    body.spine(*P['sp'])
    if any(P['neck']):
        body.p.add('neck_01', qrot(*P['neck']))
    body.clavicle('r', *P['clr'])
    body.clavicle('l', *P['cll'])
    body.head_world(*P['head'], follow=P['hf'])
    for s in 'lr':
        toe = P['toe_' + s]
        body.leg(s, Vector(P['ball_' + s]), heel=P['heel_' + s], yaw=P['fyaw_' + s],
                 toe=None if toe <= NONE + 1 else toe, knee_out=P['kout_' + s], roll=P['froll_' + s])
    for s in 'rl':
        sh = body.p.headp('upperarm_' + s)
        off = Vector(P['arm_' + s])
        arc = P['arc_' + s]
        if arc[0] > NONE + 1:
            sgn = 1 if s == 'l' else -1
            ang = math.radians(arc[0])
            off = Vector((sgn * arc[1] * math.cos(ang), -arc[1] * math.sin(ang), arc[2]))
        w = P['warm_' + s]
        target = sh + off if w <= 0 else (sh + off).lerp(off, w)
        body.arm(s, target, pole=sh + Vector(P['pole_' + s]), hand=P['hand_' + s],
                 curl=P['curl_' + s], spread=P['spr_' + s], thumb=P['th_' + s])
    body.p.add('blood_claw', qrot(0, 0, P['claw']))
    if sig is not None:
        legs = (MV.thigh_back(body, 'l') * 0.5, MV.thigh_back(body, 'r') * 0.5)
        MV.coat(body, f, sig, stream=P['stream'], spread=P['cspread'], legs=legs, settle=P['csettle'])
        MV.hair(body, f, sig, stream=P['hstream'], settle=P['hsettle'])
    body.p.solve()
    return body


def make_sig(table, length):
    """Secondary driver from the body's own motion (velocity of pelvis/chest)."""
    def s(t):
        a = params(table, max(1, min(length, t)), False, length)
        b = params(table, max(1, min(length, t - 2)), False, length)
        surge = (a['sp'][0] - b['sp'][0]) * 0.12 + (a['pelr'][0] - b['pelr'][0]) * 0.1 - (a['pel'][1] - b['pel'][1]) * 6
        sway = (a['sp'][1] - b['sp'][1]) * 0.12 + (a['pelr'][1] - b['pelr'][1]) * 0.1 + (a['pel'][0] - b['pel'][0]) * 5
        lift = (b['pel'][2] - a['pel'][2]) * 18
        return (surge, sway, lift)
    return s


def pose(rig, name, f, phase='polish'):
    A = ACTIONS[name]
    table, length = A['table'], A['length']
    polish = phase == 'polish'
    P = params(table, f, polish, length)
    sig = make_sig(table, length) if polish else None
    return apply(rig, P, sig, f)


